/// <reference types="vite/client" />

// The legal pages (site/legal.py): the refund policy and contact page exist, are linked from every
// footer and from the terms and privacy policy, and never publish placeholder text.

const pages = import.meta.glob('../*.html', { query: '?raw', import: 'default', eager: true }) as Record<string, string>;
const partials = import.meta.glob('../partials/*.html', { query: '?raw', import: 'default', eager: true }) as Record<string, string>;
const page = (name: string) => pages[`../${name}`];
const PLACEHOLDER = /x{3,}|\bTODO\b|\bTBD\b|lorem|example\.com|test@test\.com|\{\{|\$\{/i;

describe('legal pages', () => {
  it('builds the refund policy and contact page with their own addresses', () => {
    expect(page('refund-policy.html')).toContain('<link rel="canonical" href="https://afklive.in/refund-policy" />');
    expect(page('contact.html')).toContain('<link rel="canonical" href="https://afklive.in/contact" />');
    expect(page('refund-policy.html')).toContain('generated by site/legal.py');
    expect(page('contact.html')).toContain('generated by site/legal.py');
  });

  it('links all four from both footers', () => {
    for (const footer of ['footer', 'footer-hi']) {
      for (const href of ['/terms', '/privacy', '/refund-policy', '/contact']) {
        expect(partials[`../partials/${footer}.html`], `${footer} ${href}`).toContain(`href="${href}"`);
      }
    }
  });

  it('moves refunds out of the terms into the refund policy', () => {
    const terms = page('terms.html');
    expect(terms).toContain('href="/refund-policy"');
    expect(terms).not.toContain('<strong>Refunds:</strong>');
    const refunds = page('refund-policy.html');
    for (const topic of ['Cancelling', 'Changing plans', 'renew</h2>', 'When we refund', 'How refunds are paid']) {
      expect(refunds, topic).toContain(topic);
    }
    // What the billing code does: 3 days' grace, upgrades credited, no automatic charges.
    expect(refunds).toContain('3 days of grace');
    expect(refunds).toContain('never charge you automatically');
  });

  it('points terms, privacy and the refund policy at the grievance officer on the contact page', () => {
    const contact = page('contact.html');
    expect(contact).toContain('<h2 id="grievance-redressal">');
    for (const f of ['terms.html', 'privacy.html', 'refund-policy.html']) expect(page(f), f).toContain('href="/contact#grievance-redressal"');
    expect(contact).toMatch(/within 24 hours and resolve it within 15 days/);
  });

  it('leaves the server-filled details as plain fallbacks, never placeholders', () => {
    const contact = page('contact.html');
    const fills = Array.from(contact.matchAll(/<div data-fill="([a-z]+)">([\s\S]*?)<\/div>/g), (m) => [m[1], m[2]]);
    expect(fills.map(([name]) => name)).toEqual(['business', 'grievance']);
    for (const [, inner] of fills) expect(inner).not.toContain('<div'); // ContactPage.java replaces up to the first </div>
    expect(fills[1][1]).toContain('mailto:support@afklive.in');
    for (const f of ['terms.html', 'privacy.html', 'refund-policy.html', 'contact.html']) expect(page(f), f).not.toMatch(PLACEHOLDER);
  });
});
