"""Builds the AFK Live brand assets from one source of truth.

The mark: a crescent moon holding an on-air dot. "AFK": you're away (asleep, even); the dot: the
channel is still live. The wordmark is Schibsted Grotesk ExtraBold converted to outlines, so logos
never depend on a font being loaded.

Run after changing anything here (needs fonttools, brotli and Python Playwright):
    python3 brand/build.py
Outputs are committed: site/public/brand/* (served at /site/brand/), public/* for the app (PWA icons,
manifest) and src/components/brand-paths.ts (the same shapes for React).
"""
import math, pathlib, re, subprocess, tempfile
from fontTools.ttLib import TTFont
from fontTools.varLib.instancer import instantiateVariableFont
from fontTools.pens.svgPathPen import SVGPathPen
from fontTools.pens.transformPen import TransformPen

ROOT = pathlib.Path(__file__).resolve().parent.parent
SITE = ROOT / 'site/public/brand'
APP = ROOT / 'public'
FONT = ROOT / 'node_modules/@fontsource-variable/schibsted-grotesk/files/schibsted-grotesk-latin-wght-normal.woff2'

# Palette (docs/brand.md). Night and marigold are the brand; on-air red is the dot.
NIGHT, DUSK, MARIGOLD, MIST, ONAIR = '#10122A', '#1A1D3B', '#FFB627', '#EEF0FA', '#FF4438'

def f(v):
    return f'{v:.2f}'.rstrip('0').rstrip('.')

def crescent(ax, ay, ar, bx, by, br):
    """Circle A minus circle B as one path (no masks, so it can be inlined many times)."""
    d = math.hypot(bx - ax, by - ay)
    a = (ar * ar - br * br + d * d) / (2 * d)
    h = math.sqrt(ar * ar - a * a)
    mx, my = ax + a * (bx - ax) / d, ay + a * (by - ay) / d
    p1 = (mx + h * (by - ay) / d, my - h * (bx - ax) / d)
    p2 = (mx - h * (by - ay) / d, my + h * (bx - ax) / d)
    return (f'M{f(p1[0])} {f(p1[1])}A{f(ar)} {f(ar)} 0 1 0 {f(p2[0])} {f(p2[1])}'
            f'A{f(br)} {f(br)} 0 0 1 {f(p1[0])} {f(p1[1])}Z')

# On a 64 grid. The dot sits in the moon's hollow with an even gap all round.
MOON = crescent(29, 35, 24, 41, 23, 17)
DOT = (41, 23, 8)

def mark(moon=MARIGOLD, dot=ONAIR):
    x, y, r = DOT
    return f'<path fill="{moon}" d="{MOON}"/><circle fill="{dot}" cx="{x}" cy="{y}" r="{r}"/>'

def wordmark_path(text='AFK Live', wght=800, track=-0.02):
    font = instantiateVariableFont(TTFont(str(FONT)), {'wght': wght})
    gs, cmap, hmtx, upm = font.getGlyphSet(), font.getBestCmap(), font['hmtx'], font['head'].unitsPerEm
    cap = font['OS/2'].sCapHeight
    s = 1 / cap  # unit cap height; scaled where used
    pen, x = SVGPathPen(gs, ntos=lambda v: f'{v:.3f}'.rstrip('0').rstrip('.')), 0.0
    for ch in text:
        g = cmap[ord(ch)]
        gs[g].draw(TransformPen(pen, (s, 0, 0, -s, x * s, 0)))
        x += hmtx[g][0] + track * upm
    return pen.getCommands(), (x - track * upm) * s  # path with cap height 1, baseline at 0; width

WORD, WORD_W = wordmark_path()
CAP = 26  # wordmark cap height on the 64-high lockup
GAP = 14

def lockup(word_fill, moon=MARIGOLD, dot=ONAIR):
    w = 64 + GAP + WORD_W * CAP
    word = f'<path fill="{word_fill}" transform="translate({64 + GAP} {32 + CAP / 2}) scale({CAP})" d="{WORD}"/>'
    return w, f'{mark(moon, dot)}{word}'

def svg(w, h, body, bg=None, rx=0, title='AFK Live'):
    back = f'<rect width="{f(w)}" height="{f(h)}" rx="{rx}" fill="{bg}"/>' if bg else ''
    return (f'<svg xmlns="http://www.w3.org/2000/svg" viewBox="0 0 {f(w)} {f(h)}" role="img">'
            f'<title>{title}</title>{back}{body}</svg>\n')

def icon_body(scale=0.72):
    # The mark centred on its visual weight (the moon's centre is off the grid centre).
    s = scale
    return f'<g transform="translate({f(32 - 33 * s)} {f(32 - 31 * s)}) scale({f(s)})">{mark()}</g>'

def write(p, text):
    p.parent.mkdir(parents=True, exist_ok=True)
    p.write_text(text)

def main():
    write(SITE / 'mark.svg', svg(64, 64, mark()))
    w, body = lockup(MIST)
    write(SITE / 'logo-on-dark.svg', svg(w, 64, body))
    w, body = lockup(NIGHT)
    write(SITE / 'logo-on-light.svg', svg(w, 64, body))
    # The "updating" page Caddy serves while the web app restarts can't load anything, so it carries the logo inline.
    page = ROOT.parent / 'afklive-scripts/caddy/errors/index.html'
    page.write_text(re.sub(r'(<!-- brand:logo-on-light -->).*?(<!-- /brand -->)',
                           lambda m: m.group(1) + svg(w, 64, body).strip() + m.group(2), page.read_text(), flags=re.S))
    w, body = lockup(MIST, MIST, MIST)
    write(SITE / 'logo-mono-light.svg', svg(w, 64, body))
    w, body = lockup(NIGHT, NIGHT, NIGHT)
    write(SITE / 'logo-mono-dark.svg', svg(w, 64, body))
    icon = svg(64, 64, icon_body(), NIGHT, 14)
    write(SITE / 'app-icon.svg', icon)
    write(SITE / 'favicon.svg', svg(64, 64, icon_body(0.86), NIGHT, 14))

    write(ROOT / 'src/components/brand-paths.ts',
          '// Generated by brand/build.py: the mark and the wordmark as paths. Do not edit by hand.\n'
          f"export const MOON = '{MOON}';\n"
          f'export const DOT = {{ cx: {DOT[0]}, cy: {DOT[1]}, r: {DOT[2]} }};\n'
          f"export const WORD = '{WORD}';\n"
          f'export const WORD_WIDTH = {WORD_W:.4f}; // at cap height 1\n')

    # Raster icons, rendered by Chromium from the SVGs above.
    from playwright.sync_api import sync_playwright
    maskable = svg(64, 64, icon_body(0.56), NIGHT)  # full bleed, mark inside the 80% safe zone
    pngs = {
        APP / 'icon-192.png': (icon, 192), APP / 'icon-512.png': (icon, 512),
        APP / 'icon-maskable-512.png': (maskable, 512), SITE / 'apple-touch-icon.png': (svg(64, 64, icon_body(0.62), NIGHT), 180),
        SITE / 'logo-email.png': (svg(lockup(MIST)[0], 64, lockup(MIST)[1]), None),
        SITE / 'favicon-32.png': (svg(64, 64, icon_body(0.86), NIGHT, 14), 32),
        SITE / 'favicon-16.png': (svg(64, 64, icon_body(0.86), NIGHT, 14), 16),
        SITE / 'favicon-48.png': (svg(64, 64, icon_body(0.86), NIGHT, 14), 48),
    }
    with sync_playwright() as p:
        b = p.chromium.launch()
        for out, (src, size) in pngs.items():
            w, h = (size, size) if size else (round(lockup(MIST)[0] * 30 / 64), 30)  # None: the email logo, 30 px high
            pg = b.new_page(viewport={'width': w, 'height': h}, device_scale_factor=1 if size else 2)
            pg.set_content(f'<html><body style="margin:0">{src.replace("<svg ", f"<svg width=\"{w}\" height=\"{h}\" ")}</body></html>')
            out.parent.mkdir(parents=True, exist_ok=True)
            pg.screenshot(path=str(out), omit_background=True)
            pg.close()
        import base64
        ticks = ''.join(f'<line x1="{f(86*math.sin(i*math.pi/12))}" y1="{f(-86*math.cos(i*math.pi/12))}" x2="{f(80*math.sin(i*math.pi/12))}" y2="{f(-80*math.cos(i*math.pi/12))}"/>' for i in range(24))
        og = (ROOT / 'brand/og.html').read_text().replace('{{FONT}}', base64.b64encode(FONT.read_bytes()).decode()).replace('{{TICKS}}', ticks).replace('{{LOGO}}', lockup(MIST)[1]).replace('{{LOGO_W}}', f(lockup(MIST)[0]))
        pg = b.new_page(viewport={'width': 1200, 'height': 630})
        pg.set_content(og, wait_until='networkidle')
        pg.screenshot(path=str(SITE / 'og.png'))
        b.close()
    subprocess.run(['convert', str(SITE / 'favicon-16.png'), str(SITE / 'favicon-32.png'), str(SITE / 'favicon-48.png'),
                    str(ROOT.parent / 'afklive-web/src/main/resources/static/favicon.ico')], check=True)
    for n in ('favicon-16.png', 'favicon-48.png'):
        (SITE / n).unlink()

if __name__ == '__main__':
    main()
